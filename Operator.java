class Operator{
	public static void main(String[] args)
	{
		int a=10,b=20;
		System.out.println("a = "+ (a));
		System.out.println("b = "+ (b));
		System.out.println("----------");
		System.out.println("a++ = "+(a++));
		System.out.println("a = "+(a));
		System.out.println("++a  = "+ (++a));
		System.out.println("a+b = "+ (a+b));
		System.out.println("a+ --b = "+ (a+ --b));
		System.out.println("b-a= "+ (b-a));
		System.out.println("------------");
		System.out.printf("a=%d \nb=%d\n",a,b);
		System.out.println("b*a = "+ (b*a));
	}
}
